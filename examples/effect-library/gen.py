#!/usr/bin/env python3
"""Write rhythm.json + fonttext.js for the effect catalog.
python3 gen.py            -> all effects (catalog reel)
python3 gen.py k_slam     -> one effect only (standalone clip)
python3 gen.py --part 1/2 -> half of the catalog"""
import json,re,sys,pathlib
H=pathlib.Path(__file__).parent;src=(H/'../../engine/effects/fx.js').read_text(encoding='utf-8')
ids=re.findall(r"^FX\('(\w+)'",src,re.M);a=sys.argv[1:]
if a and a[0]=='--part':i,n=map(int,a[1].split('/'));k=-(-len(ids)//n);ids=ids[(i-1)*k:i*k]
elif a:ids=[x for x in a if x in ids] or sys.exit('unknown id')
shots=[{"id":x,"len":"5b","in":"cut"} for x in ids]
r={"_note":"effect catalog (generated by gen.py)","bpm":120,"beats_per_bar":4,"seed":7,"shots":shots,
 "hits":[{"id":"h0","at":"shot:"+ids[0],"type":"snap","main":True}],"marks":{},
 "sections":[{"at":0,"energy":2}],"music":{"key":"D","mode":"minor","prog":"i-VI-III-VII","drums":"broken","arp":"wave","lead":"marimba","outro":"bell","outro_at":"shot:"+ids[-1]}}
(H/'rhythm.json').write_text(json.dumps(r,ensure_ascii=False,indent=1),encoding='utf-8')
ch=sorted(set(c for c in src if ord(c)>127))
(H/'fonttext.js').write_text('const FONTTEXT='+json.dumps(''.join(ch)+'0123456789#%',ensure_ascii=False)+';',encoding='utf-8')
print(len(ids),'effects')
